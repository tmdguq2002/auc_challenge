def load_guides() -> dict[str, str]:
    from pathlib import Path
    from .dictionary import ORIGINAL_CONF_DIRS, _read
    for c in ORIGINAL_CONF_DIRS:
        p = Path(c) / "Jomun.txt"
        if p.exists():
            out = {}
            for line in _read(p).splitlines():
                if "\t" in line:
                    k, v = line.split("\t", 1)
                    if k.strip() and v.strip().startswith("http"):
                        out.setdefault(k.strip(), v.strip())
            if out:
                return out
    return dict(GUIDE_KEYWORDS)
