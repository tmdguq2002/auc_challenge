def subject_word(law_type: str) -> str:
    return {"법률": "이 법", "대통령령": "이 영", "부령": "이 규칙", "조례": "이 조례", "규칙": "이 규칙", "정관": "이 정관",
            "시행내규": "이 내규", "내규": "이 내규", "지침": "이 지침"}.get(law_type, "이 규정")


def fill(template: str, law_type: str = "규정", org: str = "공사") -> str:
    s = template.replace("{규정}", subject_word(law_type)).replace("{기관}", org)
    if law_type != "규정":
        s = s.replace("이 규정은", subject_word(law_type) + ("은" if subject_word(law_type)[-1] in "법령정칙" else "는"))
    return s


